const assert=require('node:assert/strict');
const E=require('../engine.js');require('../module-engine.js');
const B=require('../bindings-v05.js'),P=require('../data-ports-v06.js');
const I=require('../workflow-intelligence-v011.js');
const V=require('../flow-building-v012.js');
const G=require('../guided-actions-v013.js');
const p=E.blank('Guided demo');
const a=E.makeNode('set_var',320,180,{name:'price',value:'200',kind:'Number'});
const b=E.makeNode('set_var',610,180,{name:'tax_rate',value:'0.15',kind:'Number'});
const m=E.makeNode('math',900,180,{name:'tax_due',left:'price',operator:'*',right:'tax_rate'});
const out=E.makeNode('print',1190,180,{mode:'Variable / expression',value:'tax_due'});
p.nodes.push(a,b,m,out);p.edges=[[p.nodes[0],a],[a,b],[b,m],[m,out]].map(([x,y])=>({from:x.id,to:y.id,port:'next'}));
let vars=I.inspect(p,E,B,P,m.id).values;
assert.deepEqual(vars.map(v=>v.name).sort(),['price','tax_rate']);
let plan=G.plan(p,m.id,{name:'final_due',operator:'*',left:{mode:'variable',value:'price'},right:{mode:'variable',value:'tax_rate'}},vars,P);
assert.equal(plan.ok,true,plan.reason);assert.equal(plan.preview,'final_due = price * tax_rate');
assert.equal(G.plan(p,m.id,{name:'price',operator:'+',left:{mode:'number',value:'15'},right:{mode:'number',value:'25'}},vars,P).ok,false);
assert.equal(G.plan(p,m.id,{name:'total',operator:'/',left:{mode:'number',value:'20'},right:{mode:'number',value:'0'}},vars,P).warnings.length,1);
assert.equal(G.plan(p,m.id,{name:'total',operator:'+',left:{mode:'number',value:'1; import os'},right:{mode:'number',value:'2'}},vars,P).ok,false);
assert.equal(G.plan(p,m.id,{name:'tax_due',operator:'**',left:{mode:'number',value:'2'},right:{mode:'number',value:'3'}},vars,P).ok,true);
const str=G.operand({mode:'text',value:'hello\nworld'},vars);assert.equal(str.code,'"hello\\nworld"');
assert.equal(G.operand({mode:'variable',value:'later'},vars).ok,false);
const printed=G.plan(p,out.id,{mode:'variable',source:'tax_due'},I.inspect(p,E,B,P,out.id).values,P);
assert.equal(printed.ok,true,printed.reason);assert.equal(printed.params.mode,'Variable / expression');
const saved=V.saveSection(p,'Calculate invoice',[a.id,b.id,m.id]);assert.equal(saved.ok,true,saved.reason);
const audit=G.sectionAudit(p,saved.section,b.id,E,P);assert.equal(audit.ok,true);assert.ok(audit.collisions.includes('price'));assert.ok(audit.warnings.length);
assert.equal(G.renameSection(p,saved.section.id,'Updated invoice').ok,true);
assert.equal(G.renameSection(p,saved.section.id,'bad name?').ok,true);
assert.equal(G.duplicateSection(p,saved.section.id,E).ok,true);assert.equal(p.reusableSections.length,2);
assert.equal(G.renameSection(p,p.reusableSections[1].id,p.reusableSections[0].name).ok,false);
assert.equal(p.reusableSections[0].nodes.length,3);
console.log('PASS v0.13: safe guided operands, variable matching, validation, section audits, rename/copy');
