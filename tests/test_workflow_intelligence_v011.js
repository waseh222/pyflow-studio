const assert=require('node:assert/strict');
const E=require('../engine.js');
const M=require('../module-engine.js');
const B=require('../bindings-v05.js');
const P=require('../data-ports-v06.js');
const I=require('../workflow-intelligence-v011.js');
const p=E.templates.find(x=>x.id==='visual-data-links').create();
const list=I.outline(p,E);
assert.equal(list.connected.length,5);
assert.equal(list.detached.length,0);
assert.equal(list.values,3);
const target=p.nodes.find(x=>x.type==='math');
const report=I.inspect(p,E,B,P,target.id);
assert.deepEqual(report.values.map(x=>x.name),['tax_rate','price']);
assert.deepEqual(report.inputs.map(x=>x.key),['left','right']);
assert(I.compatible('integer','number'));
assert(!I.compatible('text','list'));
const before=JSON.stringify({edges:p.edges,dataLinks:p.dataLinks,params:p.nodes.map(n=>n.params)});
const organized=I.arranged(p,E);
assert.equal(Object.keys(organized).length,5);
assert.deepEqual(JSON.stringify({edges:p.edges,dataLinks:p.dataLinks,params:p.nodes.map(n=>n.params)}),before);
assert(organized[p.nodes[1].id].x<organized[p.nodes[3].id].x);
const detached=E.makeNode('print',1500,400,{value:'Hi'});p.nodes.push(detached);
const withDetached=I.outline(p,E);
assert.equal(withDetached.detached.length,1);
assert.equal(withDetached.detached[0].id,detached.id);
assert.equal(new Set(Object.values(I.arranged(p,E)).map(n=>n.x+':'+n.y)).size,6);
const starts=E.templates.map(t=>t.create());
for(const x of starts){const result=I.outline(x,E);assert.equal(result.connected.length+result.detached.length,x.nodes.length);}
console.log('PASS v0.11 workflow intelligence: upstream typed outputs, graph outline, deterministic non-destructive layout, all templates');
